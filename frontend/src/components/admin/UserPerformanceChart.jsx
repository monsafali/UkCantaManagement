import {
  ResponsiveContainer,
  BarChart,
  Bar,
  XAxis,
  YAxis,
  CartesianGrid,
  Tooltip,
} from "recharts";

export default function UserPerformanceChart({
  data,
}) {
  const chartData = data.map((item) => ({
    name:
      item.fullname ||
      item.username ||
      "User",

    entries: item.totalEntries,

    revenue: item.totalRevenue,
  }));

  return (
    <div className="bg-white rounded-2xl border shadow-sm p-6">

      <div className="mb-6">
        <h2 className="font-bold text-lg">
          User Performance
        </h2>

        <p className="text-sm text-gray-500">
          Entries and revenue generated by users
        </p>
      </div>

      <div className="h-[350px]">
        {chartData.length === 0 ? (
          <div className="h-full flex items-center justify-center text-gray-400">
            No user performance data available
          </div>
        ) : (
          <ResponsiveContainer
            width="100%"
            height="100%"
          >
            <BarChart data={chartData}>
              <CartesianGrid
                strokeDasharray="3 3"
                stroke="#e5e7eb"
              />

              <XAxis
                dataKey="name"
                tick={{
                  fontSize: 11,
                }}
              />

              <YAxis />

              <Tooltip />

              <Bar
                dataKey="entries"
                fill="#2563eb"
                name="Entries"
                radius={[5, 5, 0, 0]}
              />

              <Bar
                dataKey="revenue"
                fill="#16a34a"
                name="Revenue"
                radius={[5, 5, 0, 0]}
              />
            </BarChart>
          </ResponsiveContainer>
        )}
      </div>
    </div>
  );
}
